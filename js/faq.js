// faq.js — аккордеон вопросов. При загрузке все пункты закрыты,
// одновременно открыт не более одного (как на сайте школы).
//
// ⚠️ Неразрывные пробелы в текстах ниже — литеральный U+00A0, а НЕ сущность
// «&nbsp;»: ответы вставляются через textContent, где сущность вывелась бы
// как видимый текст «&nbsp;». В редакторе такой пробел неотличим от обычного.
(() => {
  'use strict';

  const root = document.querySelector('.faq');
  if (!root) return;

  const list = root.querySelector('.faq__list');
  if (!list) return;

  const items = [
    {
      q: 'Будет ли запись вебинара?',
      a: 'Да, запись мы пришлём всем, кто зарегистрировался, — даже если вы не смогли быть на эфире. Но бонусы участников (диагностика и скидка на первый месяц) мы отдаём тем, кто был онлайн: на эфире можно задать вопрос про своего ребёнка и сразу получить ответ.',
    },
    {
      q: 'Ребёнку 5 лет, нам ещё рано?',
      a: 'Приходите. На вебинаре мы как раз разбираем, почему слишком ранняя «посадка за парту» вредит, и что делать в 5 лет, чтобы через год ребёнок пришёл на подготовку с интересом, а не с усталостью от учёбы.',
    },
    {
      q: 'А если ребёнок уже знает буквы и считает — подготовка нужна?',
      a: 'Чаще всего да. Буквы и счёт — не то, на чём спотыкаются первоклассники. Тяжело даётся другое: высидеть урок, услышать задание с первого раза, доделать начатое, не растеряться среди двадцати сверстников. Именно это и формирует год подготовки.',
    },
    {
      q: 'Сколько стоит подготовка и что входит в занятия?',
      a: 'Стоимость и расписание мы разбираем индивидуально — они зависят от филиала и выбранного количества занятий в неделю. На бесплатной диагностике педагог посмотрит вашего ребёнка и предложит конкретный формат. Участникам вебинара первый месяц обходится вполовину дешевле.',
    },
    {
      q: 'Как проходит бесплатная диагностика готовности?',
      a: 'Это спокойная встреча ребёнка с педагогом, без экзамена и оценок: педагог смотрит внимание, речь, умение работать в паре и доводить задание до конца. После встречи вы получаете понятное заключение — что уже сформировано, а над чем стоит поработать за оставшийся год.',
    },
    {
      q: 'Обязательно ли потом идти в 1 класс «Моей школы LS»?',
      a: 'Нет. Группа подготовки — самостоятельная программа, и ребёнок после неё идёт в ту школу, которую выберет семья. Просто дети, которые готовились у нас, приходят в наш 1 класс уже своими: знают педагогов, здание и распорядок.',
    },
  ];

  // Иконка-шеврон смотрит вверх; закрытому айтему её разворачивает CSS
  const chevron =
    '<span class="faq__toggle">' +
    '<svg width="13" height="8" viewBox="0 0 14 8" fill="none" aria-hidden="true">' +
    '<path d="M0.305974 7.69397C0.50193 7.88988 0.767679 7.99994 1.04477 7.99994C1.32187 7.99994 1.58762 7.88988 1.78357 7.69397L6.95598 2.52156L12.1284 7.69397C12.3264 7.87832 12.5883 7.97868 12.8588 7.97391C13.1293 7.96915 13.3874 7.85965 13.5789 7.66843C13.7703 7.47722 13.8801 7.21921 13.8851 6.94869C13.8902 6.67817 13.7901 6.41624 13.606 6.218L7.6956 0.305974C7.49964 0.11006 7.23389 0 6.9568 0C6.6797 0 6.41396 0.11006 6.218 0.305974L0.305974 6.21637C0.11006 6.41232 0 6.67807 0 6.95517C0 7.23226 0.11006 7.49801 0.305974 7.69397Z" fill="currentColor"/>' +
    '</svg></span>';

  items.forEach((item, i) => {
    const wrap = document.createElement('div');
    wrap.className = 'faq__item';

    const id = 'faq-answer-' + i;

    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'faq__question';
    btn.setAttribute('aria-expanded', 'false');
    btn.setAttribute('aria-controls', id);

    // Вопрос — через textContent (в нём кавычки-ёлочки и имя школы),
    // шеврон дописываем разметкой отдельно.
    const qText = document.createElement('span');
    qText.className = 'faq__q-text';
    qText.textContent = item.q;
    btn.appendChild(qText);
    btn.insertAdjacentHTML('beforeend', chevron);

    const answerWrap = document.createElement('div');
    answerWrap.className = 'faq__answer-wrap';
    answerWrap.id = id;

    const answer = document.createElement('div');
    answer.className = 'faq__answer';
    const p = document.createElement('p');
    p.textContent = item.a;
    answer.appendChild(p);
    answerWrap.appendChild(answer);

    btn.addEventListener('click', () => {
      const willOpen = !wrap.classList.contains('faq__item--open');

      // Одновременно открыт только один пункт
      list.querySelectorAll('.faq__item--open').forEach((el) => {
        el.classList.remove('faq__item--open');
        el.querySelector('.faq__question').setAttribute('aria-expanded', 'false');
      });

      if (willOpen) {
        wrap.classList.add('faq__item--open');
        btn.setAttribute('aria-expanded', 'true');
      }
    });

    wrap.appendChild(btn);
    wrap.appendChild(answerWrap);
    list.appendChild(wrap);
  });
})();
